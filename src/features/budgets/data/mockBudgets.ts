export function getBudgetsForTenant(tenantId: string | number): Budget[] {
  return MOCK_BUDGETS_BY_TENANT[tenantId] ?? MOCK_BUDGETS_BY_TENANT[101]
}

export function getBudgetMetricsForTenant(tenantId: string | number): BudgetMetricsSummary {
  const budgets = getBudgetsForTenant(tenantId)
  const totalAllocated = budgets.reduce((acc, b) => acc + b.allocatedAmount, 0)
  const totalSpent = budgets.reduce((acc, b) => acc + b.spentAmount, 0)
  const totalRemaining = Math.max(0, totalAllocated - totalSpent)
  const overallConsumptionPercentage = totalAllocated > 0 ? (totalSpent / totalAllocated) * 100 : 0

  let normalCount = 0
  let warningCount = 0
  let criticalCount = 0
  let exceededCount = 0

  let highestConsumed: Budget | undefined

  for (const b of budgets) {
    if (b.consumingStatus === 'EXCEEDED') exceededCount++
    else if (b.consumingStatus === 'CRITICAL') criticalCount++
    else if (b.consumingStatus === 'WARNING') warningCount++
    else normalCount++

    if (!highestConsumed || b.consumedPercentage > highestConsumed.consumedPercentage) {
      highestConsumed = b
    }
  }

  return {
    totalAllocated,
    totalSpent,
    totalRemaining,
    overallConsumptionPercentage,
    activeBudgetsCount: budgets.length,
    normalCount,
    warningCount,
    criticalCount,
    exceededCount,
    highestConsumedBudget: highestConsumed
      ? {
          id: highestConsumed.id,
          name: highestConsumed.name,
          percentage: highestConsumed.consumedPercentage,
          spent: highestConsumed.spentAmount,
          allocated: highestConsumed.allocatedAmount,
        }
      : undefined,
  }
}
